const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, 'zh-CN': zh };

function interpolate(template: string, variables?: Variables): string {
  if (!variables) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(variables[key] ?? `{${key}}`));
}

export function translate(language: Language, key: TranslationKey, variables?: Variables): string {
  return interpolate(dictionaries[language][key], variables);
}

export function useI18n() {
  const language = useUIStore((state) => state.language);
  const t = useCallback((key: TranslationKey, variables?: Variables) => translate(language, key, variables), [language]);
  const plural = useCallback((key: TranslationKey, count: number, variables?: Variables) => {
    const pluralKey = count === 1 ? key : `${key}_other` as TranslationKey;
    const resolvedKey = pluralKey in dictionaries[language] ? pluralKey : key;
    return translate(language, resolvedKey, { ...variables, count });
  }, [language]);
  return { language, locale: language === 'zh-CN' ? 'zh-CN' : 'en-US', t, plural };
}
